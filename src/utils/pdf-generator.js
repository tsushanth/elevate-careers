// utils/pdf-generator.js
const PDFDocument = require('pdfkit');
const { PassThrough } = require('stream');

/**
 * Generate a professional PDF resume from structured data
 * @param {Object} resumeData - Structured resume data
 * @returns {Promise<Buffer>} - PDF buffer
 */
async function generateResumePDF(resumeData) {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: 'A4',
        margins: {
          top: 50,
          bottom: 50,
          left: 50,
          right: 50
        }
      });

      const buffers = [];
      
      doc.on('data', buffers.push.bind(buffers));
      doc.on('end', () => {
        const pdfBuffer = Buffer.concat(buffers);
        resolve(pdfBuffer);
      });
      doc.on('error', reject);

      // --- HEADER: Personal Info ---
      const { personalInfo } = resumeData;
      
      if (personalInfo.name) {
        doc.fontSize(24)
           .font('Helvetica-Bold')
           .text(personalInfo.name, { align: 'center' });
        doc.moveDown(0.5);
      }

      // Contact info
      const contactInfo = [];
      if (personalInfo.email) contactInfo.push(personalInfo.email);
      if (personalInfo.phone) contactInfo.push(personalInfo.phone);
      if (personalInfo.location) contactInfo.push(personalInfo.location);
      
      if (contactInfo.length > 0) {
        doc.fontSize(10)
           .font('Helvetica')
           .text(contactInfo.join(' • '), { align: 'center' });
        doc.moveDown(1);
      }

      // Divider line
      doc.moveTo(50, doc.y)
         .lineTo(545, doc.y)
         .stroke();
      doc.moveDown(1);

      // --- EDUCATION ---
      if (resumeData.education && resumeData.education.length > 0) {
        addSection(doc, 'EDUCATION');
        
        resumeData.education.forEach((edu, index) => {
          if (index > 0) doc.moveDown(0.5);
          
          // School and Degree on one line
          doc.fontSize(12)
             .font('Helvetica-Bold')
             .text(edu.school || '', { continued: false });
          
          const degreeInfo = [];
          if (edu.degree) degreeInfo.push(edu.degree);
          if (edu.field) degreeInfo.push(edu.field);
          
          if (degreeInfo.length > 0) {
            doc.fontSize(11)
               .font('Helvetica')
               .text(degreeInfo.join(' in '));
          }
          
          if (edu.graduationYear) {
            doc.fontSize(10)
               .font('Helvetica-Oblique')
               .text(`Graduated: ${edu.graduationYear}`);
          }
        });
        
        doc.moveDown(1);
      }

      // --- EXPERIENCE ---
      if (resumeData.experience && resumeData.experience.length > 0) {
        addSection(doc, 'EXPERIENCE');
        
        resumeData.experience.forEach((exp, index) => {
          if (index > 0) doc.moveDown(0.8);
          
          // Position
          if (exp.position) {
            doc.fontSize(12)
               .font('Helvetica-Bold')
               .text(exp.position);
          }
          
          // Company and Duration
          const companyInfo = [];
          if (exp.company) companyInfo.push(exp.company);
          if (exp.duration) companyInfo.push(exp.duration);
          
          if (companyInfo.length > 0) {
            doc.fontSize(11)
               .font('Helvetica-Oblique')
               .text(companyInfo.join(' • '));
          }
          
          // Responsibilities
          if (exp.responsibilities && exp.responsibilities.length > 0) {
            doc.moveDown(0.3);
            exp.responsibilities.forEach(resp => {
              doc.fontSize(10)
                 .font('Helvetica')
                 .text('• ' + resp, {
                   indent: 20,
                   paragraphGap: 3
                 });
            });
          }
        });
        
        doc.moveDown(1);
      }

      // --- SKILLS ---
      if (resumeData.skills && resumeData.skills.length > 0) {
        addSection(doc, 'SKILLS');
        
        doc.fontSize(10)
           .font('Helvetica')
           .text(resumeData.skills.join(' • '), {
             align: 'left',
             width: 495
           });
        
        doc.moveDown(1);
      }

      // Footer
      doc.fontSize(8)
         .font('Helvetica-Oblique')
         .text('Generated by ElevateCareers AI Resume Builder', 50, 770, {
           align: 'center'
         });

      doc.end();

    } catch (error) {
      reject(error);
    }
  });
}

/**
 * Add a section header to the PDF
 */
function addSection(doc, title) {
  doc.fontSize(14)
     .font('Helvetica-Bold')
     .text(title);
  
  // Underline
  const titleWidth = doc.widthOfString(title);
  doc.moveTo(50, doc.y + 2)
     .lineTo(50 + titleWidth, doc.y + 2)
     .lineWidth(1.5)
     .stroke();
  
  doc.moveDown(0.5);
}

module.exports = {
  generateResumePDF
};